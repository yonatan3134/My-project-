#!/usr/bin/env python3
"""Turn a Whisper transcript into a HyperFrames captions scene.

  python3 scripts/hf-captions.py media/transcripts/talk/talk.words.json hyperframes/projects/talk
  python3 scripts/hf-captions.py talk.words.json hyperframes/projects/talk --words 3 --color "#22d3ee"

Writes <project>/compositions/captions.html (word-highlight captions, right-to-left
aware) and copies the Heebo font into <project>/assets/fonts. Then mount it in
index.html with the snippet this prints. The scene is ordinary source: restyle it.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts" / "heebo"
SENTENCE_END = (".", "?", "!", "…")
RTL = re.compile(r"[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFF]")

TEMPLATE = """<!-- Generated by scripts/hf-captions.py from __SOURCE__. Safe to edit: restyle freely. -->
<template>
  <style>
    @font-face {
      font-family: "Heebo";
      src: url("assets/fonts/heebo-hebrew-wght-normal.woff2") format("woff2");
      font-weight: 100 900;
      unicode-range: U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F;
    }
    @font-face {
      font-family: "Heebo";
      src: url("assets/fonts/heebo-latin-wght-normal.woff2") format("woff2");
      font-weight: 100 900;
      unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC,
        U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215,
        U+FEFF, U+FFFD;
    }
    #root {
      position: absolute;
      inset: 0;
      pointer-events: none;
    }
    .cap-group {
      position: absolute;
      left: 0;
      width: 100%;
      bottom: __BOTTOM__px;
      text-align: center;
      white-space: nowrap;
      opacity: 0;
      visibility: hidden;
      font-family: "Heebo", sans-serif;
      font-weight: 800;
      line-height: 1.15;
      color: #ffffff;
      -webkit-text-stroke: 10px rgba(0, 0, 0, 0.85);
      paint-order: stroke fill;
      text-shadow: 0 6px 24px rgba(0, 0, 0, 0.45);
    }
    .cap-word {
      display: inline-block;
      margin: 0 0.14em;
    }
  </style>
  <div id="root" data-composition-id="captions" data-width="__WIDTH__" data-height="__HEIGHT__">
    <div id="cap-container" data-layout-allow-overflow></div>
  </div>
  <script>
    (function () {
      const HIGHLIGHT = "__COLOR__";
      const BASE_FONT_SIZE = __FONT_SIZE__;
      const MAX_WIDTH = __MAX_WIDTH__;
      // One entry per spoken word, in seconds from the start of the media.
      const WORDS = __WORDS__;
      // [first word, last word, right-to-left?] of every caption group.
      const GROUPS = __GROUPS__;

      const container = document.getElementById("cap-container");
      const tl = gsap.timeline({ paused: true });
      const fit = window.__hyperframes && window.__hyperframes.fitTextFontSize;

      GROUPS.forEach(function (range, index) {
        const words = WORDS.slice(range[0], range[1] + 1);
        const next = GROUPS[index + 1];
        const start = Math.max(0.1, words[0].start);
        const end = Math.min(
          words[words.length - 1].end + 0.4,
          next ? WORDS[next[0]].start - 0.04 : Infinity,
        );

        const group = document.createElement("div");
        group.className = "cap-group";
        group.id = "cap-g-" + index;
        group.dir = range[2] ? "rtl" : "ltr";
        const text = words.map(function (w) { return w.text; }).join(" ");
        const fitted = fit
          ? fit(text, { fontFamily: "Heebo", fontWeight: 800, maxWidth: MAX_WIDTH, baseFontSize: BASE_FONT_SIZE })
          : null;
        group.style.fontSize = Math.min(BASE_FONT_SIZE, fitted ? fitted.fontSize : BASE_FONT_SIZE) + "px";

        words.forEach(function (w, i) {
          const span = document.createElement("span");
          span.className = "cap-word";
          span.id = "cap-w-" + (range[0] + i);
          span.textContent = w.text;
          group.appendChild(span);
          tl.fromTo(span, { color: "#ffffff" }, { color: HIGHLIGHT, duration: 0.06, ease: "power2.out" }, Math.max(start, w.start));
          tl.to(span, { color: "#ffffff", duration: 0.1, ease: "power2.in" }, Math.max(start + 0.06, Math.min(w.end, end - 0.12)));
        });
        container.appendChild(group);

        tl.set(group, { visibility: "visible" }, start);
        tl.fromTo(group, { opacity: 0, scale: 0.9 }, { opacity: 1, scale: 1, duration: 0.14, ease: "back.out(1.6)" }, start);
        tl.to(group, { opacity: 0, duration: 0.1, ease: "power2.in" }, end - 0.1);
        tl.set(group, { opacity: 0, visibility: "hidden" }, end);
      });

      window.__timelines["captions"] = tl;
    })();
  </script>
</template>
"""


def build_groups(words: list[dict], max_words: int) -> list[list]:
    """Phrases end at a sentence end or a pause; each is cut into even groups, so no word is left alone."""
    phrases: list[list[int]] = []
    for index, word in enumerate(words):
        if phrases:
            previous = words[phrases[-1][-1]]
            if word["start"] - previous["end"] < 0.3 and not previous["text"].endswith(SENTENCE_END):
                phrases[-1].append(index)
                continue
        phrases.append([index])

    groups = []
    for phrase in phrases:
        parts = math.ceil(len(phrase) / max_words)
        for part in range(parts):
            chunk = phrase[round(part * len(phrase) / parts) : round((part + 1) * len(phrase) / parts)]
            texts = [words[i]["text"] for i in chunk]
            rtl = sum(1 for t in texts if RTL.search(t)) > len(texts) / 2
            groups.append([chunk[0], chunk[-1], rtl])
    return groups


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate a HyperFrames captions scene from <name>.words.json.")
    parser.add_argument("words", help="<name>.words.json written by scripts/transcribe.sh")
    parser.add_argument("project", help="HyperFrames project folder (the one with index.html)")
    parser.add_argument("--words-per-group", "--words", type=int, help="default 4 (3 for vertical video)")
    parser.add_argument("--color", default="#facc15", help="colour of the word being spoken")
    args = parser.parse_args()

    words_path = Path(args.words).expanduser().resolve()
    project = Path(args.project).expanduser().resolve()
    index_html = project / "index.html"
    if not index_html.is_file():
        sys.exit(f"No index.html in {project}. Create the project first: npx hyperframes init <dir> --skip-skills")

    words = [
        {"text": w["text"], "start": round(float(w["start"]), 3), "end": round(float(w["end"]), 3)}
        for w in json.loads(words_path.read_text(encoding="utf-8"))
        if w.get("text", "").strip()
    ]
    if not words:
        sys.exit("The transcript has no words.")

    html = index_html.read_text(encoding="utf-8")
    width = int(m.group(1)) if (m := re.search(r'data-width="(\d+)"', html)) else 1920
    height = int(m.group(1)) if (m := re.search(r'data-height="(\d+)"', html)) else 1080
    portrait = height > width
    per_group = args.words_per_group or (3 if portrait else 4)

    scene = (
        TEMPLATE.replace("__SOURCE__", words_path.name)
        .replace("__WIDTH__", str(width))
        .replace("__HEIGHT__", str(height))
        .replace("__BOTTOM__", str(round(height * 0.33) if portrait else 100))
        .replace("__FONT_SIZE__", str(round(width * 0.085) if portrait else 78))
        .replace("__MAX_WIDTH__", str(round(width * 0.84)))
        .replace("__COLOR__", args.color)
        .replace("__WORDS__", json.dumps(words, ensure_ascii=False))
        .replace("__GROUPS__", json.dumps(build_groups(words, per_group)))
    )
    (project / "compositions").mkdir(exist_ok=True)
    (project / "compositions" / "captions.html").write_text(scene, encoding="utf-8")

    fonts = project / "assets" / "fonts"
    fonts.mkdir(parents=True, exist_ok=True)
    for font in FONT_DIR.glob("*.woff2"):
        shutil.copy2(font, fonts / font.name)

    root_duration = float(m.group(1)) if (m := re.search(r'data-duration="([\d.]+)"', html)) else None
    duration = round(words[-1]["end"] + 0.5, 2)
    if root_duration is not None:
        duration = min(duration, root_duration)
    print(f"Wrote {project / 'compositions' / 'captions.html'} ({len(words)} words)")
    print("Mount it inside the root composition of index.html (keep it within the root's data-duration):\n")
    print(
        f'<div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html"\n'
        f'     data-start="0" data-duration="{duration}" data-track-index="9" data-track-kind="captions"\n'
        f'     data-width="{width}" data-height="{height}" style="z-index: 9"></div>'
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
